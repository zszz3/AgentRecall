import { z } from "zod";
import { assetId } from "./asset-paths.js";

export const REVIEW_RULES_FILE = "OWNERS.json";
export const CODEOWNERS_FILE = ".github/CODEOWNERS";
export const REVIEW_RULES_ID = "review-rules";

/** Resource kinds that review rules may name; `kind` alone covers every item of that kind. */
export const REVIEW_KINDS = ["skills", "documents", "instructions", "mcp", "environment", "organization", "reviewRules"] as const;
const reviewKind = z.enum(REVIEW_KINDS);
const resource = z.string().max(200).refine((value) => {
  const [kind, id, extra] = value.split(":");
  if (extra !== undefined || !reviewKind.safeParse(kind).success) return false;
  if (id === undefined) return true;
  return kind === "environment" ? /^[A-Za-z_][A-Za-z0-9_]{0,127}$/.test(id) : kind !== "reviewRules" && assetId.safeParse(id).success;
});
/** GitHub user (`@name`) or team (`@org/team`) handles, the same syntax CODEOWNERS accepts. */
const owner = z.string().regex(/^@[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})(?:\/[A-Za-z0-9][A-Za-z0-9._-]{0,99})?$/);
const unique = (items: string[]) => new Set(items.map((item) => item.toLowerCase())).size === items.length;
export const reviewRuleSchema = z.strictObject({
  resources: z.array(resource).min(1).max(64).refine(unique),
  owners: z.array(owner).min(1).max(16).refine(unique),
});
export const reviewRulesSchema = z.strictObject({ schemaVersion: z.literal(1), rules: z.array(reviewRuleSchema).max(64) });
export const reviewRulesChangeSchema = z.strictObject({
  kind: z.literal("reviewRules"),
  operation: z.enum(["create", "update"]),
  value: z.strictObject({ id: z.literal(REVIEW_RULES_ID), name: z.string().trim().min(1).max(200), rules: z.array(reviewRuleSchema).max(64) }),
});
export type ReviewRules = z.infer<typeof reviewRulesSchema>;
export type ReviewRulesChange = z.infer<typeof reviewRulesChangeSchema>;

/**
 * Returns the owners that must review a change to the given item keys
 * (`kind:id`, or `environment:NAME`). Environment names match case-insensitively
 * because the manifest treats them that way.
 */
export function reviewOwners(rules: ReviewRules | null, itemKey: string): string[] {
  if (!rules) return [];
  const [kind] = itemKey.split(":");
  const owners = new Map<string, string>();
  for (const rule of rules.rules) {
    if (!rule.resources.some((value) => value === kind || (kind === "environment" ? value.toLowerCase() === itemKey.toLowerCase() : value === itemKey))) continue;
    for (const handle of rule.owners) if (!owners.has(handle.toLowerCase())) owners.set(handle.toLowerCase(), handle);
  }
  return [...owners.values()];
}

/**
 * Renders GitHub CODEOWNERS for the rules. AgentRecall routes by resource;
 * GitHub only routes by path, so resources that live inside the manifest map to
 * `agentrecall.json`, which every published change also touches. The file is a
 * convenience for branch protection, not the source of truth.
 */
export function renderCodeOwners(rules: ReviewRules, paths: (resource: string) => string[]): string {
  const lines = ["# Generated by AgentRecall from OWNERS.json. Edit review rules in AgentRecall instead of this file.", ""];
  // GitHub applies only the last matching line, so owners of one path are merged into one line.
  const byPattern = new Map<string, Set<string>>();
  for (const rule of rules.rules) {
    for (const pattern of rule.resources.flatMap(paths)) {
      const owners = byPattern.get(pattern) ?? new Set<string>();
      rule.owners.forEach((handle) => owners.add(handle));
      byPattern.set(pattern, owners);
    }
  }
  // A deeper path line replaces a directory line in GitHub, so it inherits that directory's owners.
  for (const [pattern, owners] of byPattern) {
    for (const [parent, inherited] of byPattern) if (parent !== pattern && parent.endsWith("/") && pattern.startsWith(parent)) inherited.forEach((handle) => owners.add(handle));
  }
  const ordered = [...byPattern].sort(([a], [b]) => a.length - b.length || a.localeCompare(b));
  for (const [pattern, owners] of ordered) lines.push(`${pattern} ${[...owners].join(" ")}`);
  return lines.join("\n") + "\n";
}
